#!/usr/bin/env python3
"""Compile the Turnip smoke shaders (drivers/AdrenoMetal/shaders, GLSL) to SPIR-V with glslc or glslangValidator and write
build/turnip-smoke/NativeTurnipShaders.h (word arrays). Build product only; the GLSL is the source."""
import argparse
from pathlib import Path
import struct
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--compiler', type=Path, default=Path('glslc'),
                    help='glslc or glslangValidator executable')
parser.add_argument('--skip-validation', action='store_true',
                    help='compile shaders without invoking spirv-val')
args = parser.parse_args()
OUT = ROOT / 'build/turnip-smoke'
OUT.mkdir(parents=True, exist_ok=True)
lines = ['// Generated by scripts/gen-turnip-smoke-shaders.py from drivers/AdrenoMetal/shaders; do not edit.', '#pragma once', '#include <stdint.h>']
with tempfile.TemporaryDirectory(prefix='.shader-', dir=OUT) as tmp:
    for source in sorted((ROOT / 'drivers/AdrenoMetal/shaders').glob('smoke_*')):
        spv = Path(tmp) / (source.name + '.spv')
        if args.compiler.name in ('glslang', 'glslangValidator'):
            command = [str(args.compiler), '-V', '--target-env', 'vulkan1.1', str(source), '-o', str(spv)]
        else:
            command = [str(args.compiler), '--target-env=vulkan1.1', '-O', str(source), '-o', str(spv)]
        subprocess.run(command, check=True)
        if not args.skip_validation:
            subprocess.run(['spirv-val', '--target-env', 'vulkan1.1', str(spv)], check=True)
        data = spv.read_bytes()
        words = struct.unpack('<%dI' % (len(data) // 4), data)
        name = 'kSpv_' + source.name.replace('.', '_')
        lines.append('static const uint32_t %s[] = {' % name)
        for i in range(0, len(words), 8):
            lines.append('    ' + ', '.join('0x%08x' % w for w in words[i:i + 8]) + ',')
        lines.append('};')
(OUT / 'NativeTurnipShaders.h').write_text('\n'.join(lines) + '\n')
print('PASS: smoke shaders compiled ->', OUT / 'NativeTurnipShaders.h')
